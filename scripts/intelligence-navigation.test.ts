import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const read = (path: string) => readFileSync(path, "utf8");
const root = process.cwd();
const layout = read(`${root}/src/app/(app)/layout.tsx`);
const sidebar = read(`${root}/src/components/Sidebar.tsx`);
const topBar = read(`${root}/src/components/TopBar.tsx`);
const primaryNavigation = read(`${root}/src/lib/primaryNavigation.ts`);
const dataApps = read(`${root}/src/app/(app)/data-apps/page.tsx`);
const appPage = read(`${root}/src/app/(app)/data-apps/[appId]/page.tsx`);
const middleware = read(`${root}/src/middleware.ts`);

assert.match(layout, /getOrgContext/);
assert.match(layout, /<AppShell hasOrganization=\{!!orgContext\}>/);
assert.match(primaryNavigation, /href: "\/data-apps\/intelligence-subscriptions"/);
assert.match(primaryNavigation, /label: "投资情报"/);
assert.match(sidebar, /hasOrganization/);
assert.match(sidebar, /label: "机构与市场数据"/);
assert.match(sidebar, /desc: "市场洞察与机构点查"/);
assert.doesNotMatch(sidebar, /情报订制与机构数据/);
assert.doesNotMatch(sidebar, /session\.user\.orgId/);
assert.match(dataApps, /const accessibleApps = DATA_APPS\.filter/);
assert.match(dataApps, /app\.availableToPersonal === true/);
assert.match(dataApps, /app\.id !== "intelligence-subscriptions"/);
assert.match(dataApps, />机构与市场数据</);
assert.match(dataApps, /accessibleApps\.length === 0/);
assert.doesNotMatch(dataApps, /机构数据能力暂未开通/);
assert.match(appPage, /app\.availableToPersonal === true/);
assert.match(appPage, /const isIntelligence =/);
assert.match(appPage, /isIntelligence \? "工作台" : "机构与市场数据"/);
assert.match(appPage, /isIntelligence \? "投资情报"/);
assert.match(topBar, /pathname\.startsWith\("\/data-apps\/intelligence-subscriptions"\)/);
assert.match(topBar, /\{ label: "投资情报" \}/);
assert.match(topBar, /\{ label: "机构与市场数据" \}/);
assert.match(middleware, /isIntelligenceSubscriptionRoute/);
assert.match(middleware, /!isIntelligenceSubscriptionRoute/);
const dashboard = read(`${root}/src/app/(app)/dashboard/page.tsx`);
const dashboardAttention = read(`${root}/src/components/dashboard/IntelligenceAttention.tsx`);
assert.match(dashboard, /IntelligenceAttention/);
assert.match(dashboard, /intelligence_tasks/);
assert.match(dashboardAttention, /href="\/data-apps\/intelligence-subscriptions"/);
assert.match(dashboardAttention, /开始订制/);
assert.match(dashboardAttention, /生成本期简报/);
assert.match(dashboardAttention, /查看简报与历史/);
assert.match(dashboardAttention, /正在打开运行进度/);
assert.match(dashboard, /进入情报工作空间/);
const topicView = read(`${root}/src/components/data-apps/IntelligenceTopicView.tsx`);
assert.match(topicView, /默认使用系统赠送的 AI 额度/);
assert.match(topicView, /已加入队列，等待后台研究开始/);
assert.doesNotMatch(topicView, /仅本次允许使用我的 DeepSeek 模型与 Search/);
console.log("intelligence navigation tests passed");
